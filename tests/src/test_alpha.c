enum {
    SIDE = 16,
};

typedef struct {
    uint64_t a, d, p, w;
    ph_digest_t bmh, color;
} hashes_t;

static void hash_ctx(ph_context_t *ctx, hashes_t *out) {
    memset(out, 0, sizeof(*out));
    ASSERT_OK(ph_compute_ahash(ctx, &out->a));
    ASSERT_OK(ph_compute_dhash(ctx, &out->d));
    ASSERT_OK(ph_compute_phash(ctx, &out->p));
    ASSERT_OK(ph_compute_whash(ctx, &out->w));
    ASSERT_OK(ph_compute_bmh(ctx, &out->bmh));
    if (ctx->image.channels >= 3) {
        ASSERT_OK(ph_compute_color_hash(ctx, &out->color));
    }
}

static int hashes_equal(const hashes_t *x, const hashes_t *y) {
    return x->a == y->a && x->d == y->d && x->p == y->p && x->w == y->w &&
           memcmp(&x->bmh, &y->bmh, sizeof(x->bmh)) == 0 &&
           memcmp(&x->color, &y->color, sizeof(x->color)) == 0;
}

static ph_context_t *load_png(const uint8_t *png, size_t len, ph_alpha_mode_t mode, int gray) {
    ph_context_t *ctx = NULL;
    ASSERT_OK(ph_create(&ctx));
    ASSERT_OK(ph_context_set_alpha_mode(ctx, mode));
    ASSERT_OK(ph_context_set_load_grayscale(ctx, gray));
    ASSERT_OK(ph_load_from_memory(ctx, png, len));
    return ctx;
}

static void hash_png(const uint8_t *png, size_t len, ph_alpha_mode_t mode, hashes_t *out) {
    ph_context_t *ctx = load_png(png, len, mode, 0);
    ASSERT_INT_EQ(3, ctx->image.channels); /* alpha resolved, never stored */
    hash_ctx(ctx, out);
    ph_free(ctx);
}

/* Two files that differ only in the colour under alpha 0 look the same, and hash the same
 * under every blending mode. With alpha dropped they are different pictures. */
static void test_hidden_colour_does_not_reach_the_hash(void) {
    static const ph_alpha_mode_t blend[] = {PH_ALPHA_BLEND_GREY, PH_ALPHA_BLEND_WHITE,
                                            PH_ALPHA_BLEND_BLACK};
    for (size_t m = 0; m < sizeof(blend) / sizeof(blend[0]); m++) {
        hashes_t black, white;
        hash_png(rgba_hidden_black_png, sizeof(rgba_hidden_black_png), blend[m], &black);
        hash_png(rgba_hidden_white_png, sizeof(rgba_hidden_white_png), blend[m], &white);
        ASSERT(hashes_equal(&black, &white));
    }

    hashes_t black, white;
    hash_png(rgba_hidden_black_png, sizeof(rgba_hidden_black_png), PH_ALPHA_IGNORE, &black);
    hash_png(rgba_hidden_white_png, sizeof(rgba_hidden_white_png), PH_ALPHA_IGNORE, &white);
    ASSERT(ph_hamming_distance(black.a, white.a) > 10);

    PASS("test_hidden_colour_does_not_reach_the_hash");
}

/* The decoder path and the pixel path resolve alpha identically: the same RGBA pixels given
 * to ph_load_from_pixels() hash the same as the PNG, in every mode, and the stored colour
 * is the documented blend. */
static void test_file_and_pixels_agree(void) {
    uint8_t rgba[SIDE * SIDE * 4];
    for (int y = 0; y < SIDE; y++) {
        for (int x = 0; x < SIDE; x++) {
            uint8_t *p = &rgba[(y * SIDE + x) * 4];
            int visible = ((x / 4 + y / 4) % 2) == 0;
            p[0] = visible ? (uint8_t)((x * 16) & 255) : 0;
            p[1] = visible ? (uint8_t)((y * 16) & 255) : 0;
            p[2] = visible ? 200 : 0;
            p[3] = visible ? 255 : 0;
        }
    }

    static const ph_alpha_mode_t modes[] = {PH_ALPHA_BLEND_GREY, PH_ALPHA_BLEND_WHITE,
                                            PH_ALPHA_BLEND_BLACK, PH_ALPHA_IGNORE};
    static const uint8_t background[] = {128, 255, 0, 0};
    for (size_t m = 0; m < sizeof(modes) / sizeof(modes[0]); m++) {
        hashes_t from_file, from_pixels;
        hash_png(rgba_hidden_black_png, sizeof(rgba_hidden_black_png), modes[m], &from_file);

        ph_context_t *ctx = NULL;
        ASSERT_OK(ph_create(&ctx));
        ASSERT_OK(ph_context_set_alpha_mode(ctx, modes[m]));
        ASSERT_OK(ph_load_from_pixels(ctx, rgba, SIDE, SIDE, 4, 0));
        ASSERT_INT_EQ(3, ctx->image.channels);
        /* (4, 0) is transparent: the background, or under IGNORE the stored black. */
        for (int c = 0; c < 3; c++) {
            ASSERT_UINT8_EQ(background[m], ctx->image.raw_rgb[4 * 3 + c]);
        }
        hash_ctx(ctx, &from_pixels);
        ph_free(ctx);

        ASSERT(hashes_equal(&from_file, &from_pixels));
    }

    /* Partial alpha: (c * a + bg * (255 - a) + 127) / 255, per channel. */
    uint8_t px[4] = {200, 100, 0, 64};
    ph_context_t *ctx = NULL;
    ASSERT_OK(ph_create(&ctx));
    ASSERT_OK(ph_load_from_pixels(ctx, px, 1, 1, 4, 0));
    ASSERT_UINT8_EQ((200 * 64 + 128 * 191 + 127) / 255, ctx->image.raw_rgb[0]);
    ASSERT_UINT8_EQ((100 * 64 + 128 * 191 + 127) / 255, ctx->image.raw_rgb[1]);
    ASSERT_UINT8_EQ((0 * 64 + 128 * 191 + 127) / 255, ctx->image.raw_rgb[2]);
    ph_free(ctx);

    PASS("test_file_and_pixels_agree");
}

/* Gray + alpha and a truecolour tRNS chunk are alpha too: loaded in colour they come back
 * as RGB, loaded as grayscale as one channel, and transparent pixels take the background
 * whatever the stored value. */
static void test_gray_alpha_and_trns(void) {
    ph_context_t *ctx = load_png(gray_alpha_png, sizeof(gray_alpha_png), PH_ALPHA_BLEND_WHITE, 0);
    ASSERT_INT_EQ(3, ctx->image.channels);
    /* (4, 0) is gray 64 at alpha 32, blended onto white; (0, 0) is opaque 0. */
    ASSERT_UINT8_EQ((64 * 32 + 255 * 223 + 127) / 255, ctx->image.raw_rgb[4 * 3]);
    ASSERT_UINT8_EQ(0, ctx->image.raw_rgb[0]);
    hashes_t color_load;
    hash_ctx(ctx, &color_load);
    ph_free(ctx);

    ctx = load_png(gray_alpha_png, sizeof(gray_alpha_png), PH_ALPHA_BLEND_WHITE, 1);
    ASSERT_INT_EQ(1, ctx->image.channels);
    ASSERT_UINT8_EQ((64 * 32 + 255 * 223 + 127) / 255, ctx->image.raw_rgb[4]);
    hashes_t gray_load;
    hash_ctx(ctx, &gray_load);
    ph_free(ctx);
    /* A gray image converts to itself, so both loads hash alike. */
    ASSERT_UINT64_EQ(color_load.a, gray_load.a);
    ASSERT_UINT64_EQ(color_load.p, gray_load.p);

    ctx = load_png(rgb_trns_png, sizeof(rgb_trns_png), PH_ALPHA_BLEND_WHITE, 0);
    ASSERT_INT_EQ(3, ctx->image.channels);
    for (int c = 0; c < 3; c++) {
        ASSERT_UINT8_EQ(255, ctx->image.raw_rgb[4 * 3 + c]); /* tRNS colour (1,2,3) */
    }
    ph_free(ctx);

    PASS("test_gray_alpha_and_trns");
}

static void test_setter_rejects_unknown_modes(void) {
    ph_context_t *ctx = NULL;
    ASSERT_OK(ph_create(&ctx));
    ASSERT_INT_EQ(PH_ALPHA_BLEND_GREY, ctx->config.alpha_mode);
    ASSERT_OK(ph_context_set_alpha_mode(ctx, PH_ALPHA_IGNORE));
    ASSERT_INT_EQ(PH_ERR_INVALID_ARGUMENT, ph_context_set_alpha_mode(ctx, (ph_alpha_mode_t)4));
    ASSERT_INT_EQ(PH_ERR_INVALID_ARGUMENT, ph_context_set_alpha_mode(ctx, (ph_alpha_mode_t)-1));
    ASSERT_INT_EQ(PH_ALPHA_IGNORE, ctx->config.alpha_mode);
    ASSERT_INT_EQ(PH_ERR_INVALID_ARGUMENT, ph_context_set_alpha_mode(NULL, PH_ALPHA_IGNORE));
    ph_free(ctx);
    PASS("test_setter_rejects_unknown_modes");
}

int main(void) {
    test_hidden_colour_does_not_reach_the_hash();
    test_file_and_pixels_agree();
    test_gray_alpha_and_trns();
    test_setter_rejects_unknown_modes();
    printf("test_alpha: PASSED\n");
    return 0;
}
